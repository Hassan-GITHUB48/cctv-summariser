import type { DetectionEvent, JobStatus, Report } from '../api'
import { timeRange } from './format'
import { severityStyle } from './severity'

/** Render a job's report as a self-contained Markdown document. */
export function reportToMarkdown(job: JobStatus, report: Report, events: DetectionEvent[]): string {
  const counts = new Map<string, number>()
  for (const e of events) counts.set(e.label, (counts.get(e.label) ?? 0) + 1)
  const meta = job.meta
  const incidents = [...report.incidents].sort((a, b) => a.start_s - b.start_s)

  const lines = [
    `# Incident report: ${job.source}`,
    '',
    `- **Job:** ${job.job_id}`,
    `- **Generated:** ${new Date(report.created_at).toISOString()} by ${report.model}`,
    meta ? `- **Video:** ${meta.duration_s.toFixed(1)}s, ${meta.width}x${meta.height}, ${meta.fps} fps` : null,
    `- **Detections:** ${[...counts].map(([label, n]) => `${label} ${n}`).join(', ') || 'none'}`,
    '',
    '## Summary',
    '',
    report.summary,
    '',
    `## Incidents (${incidents.length})`,
    '',
  ]
  if (incidents.length === 0) lines.push('No incidents.', '')
  for (const inc of incidents) {
    lines.push(
      `### [${timeRange(inc.start_s, inc.end_s)}] ${inc.title}`,
      '',
      `**Severity:** ${inc.severity}/5 (${severityStyle(inc.severity).label})  `,
      `**Recommended action:** ${inc.recommended_action}`,
      '',
      inc.description,
      '',
    )
  }
  lines.push('---', '_Generated by CCTV Incident Summariser from automated detections; verify against footage._', '')
  return lines.filter((l) => l !== null).join('\n')
}

export function downloadText(filename: string, text: string, type = 'text/markdown'): void {
  const url = URL.createObjectURL(new Blob([text], { type }))
  const a = Object.assign(document.createElement('a'), { href: url, download: filename })
  a.click()
  URL.revokeObjectURL(url)
}
